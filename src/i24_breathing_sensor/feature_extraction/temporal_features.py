
"""
Temporal Feature Extraction
===========================

Calculates respiratory timing features from validated
respiratory cycles generated by the event detection module.

No additional peak detection is performed here.
"""

import numpy as np

from .models import TemporalFeatureResult


def _calculate_statistics(values):
    """Calculate basic summary statistics for feature values."""

    valid = [
        float(value)
        for value in values
        if value is not None and np.isfinite(value)
    ]

    if not valid:
        return {
            "mean": None,
            "median": None,
            "std": None,
            "min": None,
            "max": None,
        }

    array = np.asarray(valid, dtype=float)

    return {
        "mean": float(np.mean(array)),
        "median": float(np.median(array)),
        "std": float(np.std(array)),
        "min": float(np.min(array)),
        "max": float(np.max(array)),
    }


def extract_temporal_features(
    detection_result,
    inhalation_phase=None,
    pause_threshold_s=None,
    include_rejected=False,
):
    """
    Extract temporal features from respiratory cycles.

    Parameters
    ----------
    detection_result:
        EventDetectionResult from the event detection module.

    inhalation_phase:
        "phase_1", "phase_2", or None.

        Must be established experimentally before assigning
        inspiration and expiration labels.

    pause_threshold_s:
        Optional threshold for flagging prolonged
        inter-trough intervals as pause candidates.

    include_rejected:
        Include rejected cycles in feature calculations if True.

    Returns
    -------
    TemporalFeatureResult
    """

    if inhalation_phase not in (None, "phase_1", "phase_2"):
        raise ValueError(
            "inhalation_phase must be None, 'phase_1' or 'phase_2'."
        )

    if pause_threshold_s is not None and pause_threshold_s <= 0:
        raise ValueError("Pause threshold must be positive.")

    # ---------------------------------------------------------
    # 1. Select cycles
    # ---------------------------------------------------------

    if include_rejected:
        cycles = detection_result.cycles
    else:
        cycles = detection_result.valid_cycles

    cycles = sorted(
        cycles,
        key=lambda cycle: cycle.start_trough.sample_index
    )

    per_cycle = []
    pause_candidates = []

    # ---------------------------------------------------------
    # 2. Calculate features per respiratory cycle
    # ---------------------------------------------------------

    for cycle in cycles:

        cycle_duration = float(cycle.duration_s)

        if cycle_duration <= 0:
            continue

        start_time = float(cycle.start_trough.time_s)
        end_time = float(cycle.end_trough.time_s)

        # Inter-breath interval:
        # Current trough to next trough.
        ibi = end_time - start_time

        respiratory_rate = 60.0 / cycle_duration

        phase_1 = cycle.phase_1_duration_s
        phase_2 = cycle.phase_2_duration_s

        inhalation_duration = None
        exhalation_duration = None

        ie_ratio = None
        inspiratory_duty_cycle = None

        # -----------------------------------------------------
        # 3. Assign physiological respiratory phases
        # -----------------------------------------------------

        if phase_1 is not None and phase_2 is not None:

            if inhalation_phase == "phase_1":

                inhalation_duration = float(phase_1)
                exhalation_duration = float(phase_2)

            elif inhalation_phase == "phase_2":

                inhalation_duration = float(phase_2)
                exhalation_duration = float(phase_1)

            if inhalation_phase is not None:

                if exhalation_duration > 0:

                    ie_ratio = (
                        inhalation_duration / exhalation_duration
                    )

                inspiratory_duty_cycle = (
                    inhalation_duration / cycle_duration
                )

        # -----------------------------------------------------
        # 4. Detect prolonged inter-breath intervals
        # -----------------------------------------------------

        pause_candidate = False
        pause_candidate_interval = None

        if pause_threshold_s is not None:

            if ibi >= pause_threshold_s:

                pause_candidate = True
                pause_candidate_interval = ibi

                pause_candidates.append({
                    "cycle_index": cycle.cycle_index,
                    "start_time_s": start_time,
                    "end_time_s": end_time,
                    "interval_duration_s": ibi,
                })

        # -----------------------------------------------------
        # 5. Store individual cycle features
        # -----------------------------------------------------

        feature_row = {

            "cycle_index": cycle.cycle_index,

            "cycle_start_time_s": start_time,

            "cycle_end_time_s": end_time,

            # Fundamental timing features
            "respiratory_rate_bpm": respiratory_rate,

            "inter_breath_interval_s": ibi,

            "respiratory_cycle_duration_s": cycle_duration,

            # Respiratory phases
            "phase_1_duration_s": phase_1,

            "phase_2_duration_s": phase_2,

            "inhalation_duration_s": inhalation_duration,

            "exhalation_duration_s": exhalation_duration,

            "ie_ratio": ie_ratio,

            "inspiratory_duty_cycle": inspiratory_duty_cycle,

            # Pause candidates
            "pause_candidate": pause_candidate,

            "pause_candidate_interval_s": pause_candidate_interval,

            # Cycle validation
            "cycle_valid": cycle.is_valid,
        }

        per_cycle.append(feature_row)

    # ---------------------------------------------------------
    # 6. Calculate summary statistics
    # ---------------------------------------------------------

    summary = {

        "total_cycles_analyzed": len(per_cycle),

        "pause_candidate_count": len(pause_candidates),

        "respiratory_rate_bpm": _calculate_statistics([
            row["respiratory_rate_bpm"]
            for row in per_cycle
        ]),

        "inter_breath_interval_s": _calculate_statistics([
            row["inter_breath_interval_s"]
            for row in per_cycle
        ]),

        "respiratory_cycle_duration_s": _calculate_statistics([
            row["respiratory_cycle_duration_s"]
            for row in per_cycle
        ]),

        "inhalation_duration_s": _calculate_statistics([
            row["inhalation_duration_s"]
            for row in per_cycle
        ]),

        "exhalation_duration_s": _calculate_statistics([
            row["exhalation_duration_s"]
            for row in per_cycle
        ]),

        "ie_ratio": _calculate_statistics([
            row["ie_ratio"]
            for row in per_cycle
        ]),

        "inspiratory_duty_cycle": _calculate_statistics([
            row["inspiratory_duty_cycle"]
            for row in per_cycle
        ]),
    }

    return TemporalFeatureResult(
        per_cycle=per_cycle,
        summary=summary,
        pause_candidates=pause_candidates,
    )
